import { writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const owner = "DeeJanuz";
const repo = "frametop";
const branch = "main";
const repoUrl = `https://github.com/${owner}/${repo}`;
const outputPath = path.join(process.cwd(), "src/data/frametop-readme.ts");

async function fetchOk(url, init) {
  const response = await fetch(url, init);

  if (!response.ok) {
    throw new Error(`${url} returned ${response.status} ${response.statusText}`);
  }

  return response;
}

async function fetchBranchHead() {
  const response = await fetchOk(
    `https://api.github.com/repos/${owner}/${repo}/commits/${branch}`,
    { headers: { Accept: "application/vnd.github+json" } },
  );
  const commit = await response.json();

  return {
    sha: commit.sha,
    date: commit.commit.committer.date.slice(0, 10),
  };
}

async function fetchReadme(sha) {
  const response = await fetchOk(
    `https://raw.githubusercontent.com/${owner}/${repo}/${sha}/README.md`,
  );

  return response.text();
}

function renderModule({ commit, markdown }) {
  const lines = markdown.replace(/\r\n/g, "\n").replace(/\n+$/, "").split("\n");
  const markdownLines = lines
    .map((line) => `    ${JSON.stringify(line)},`)
    .join("\n");

  return `// Generated by scripts/sync-frametop-readme.mjs. Do not edit by hand.
// Refresh with \`npm run sync:frametop-readme\`.
import type { ProjectReadmeSnapshot } from "@/types";

export const frametopReadme = {
  title: "Frametop",
  repoUrl: ${JSON.stringify(repoUrl)},
  branch: ${JSON.stringify(branch)},
  commitSha: ${JSON.stringify(commit.sha)},
  commitDate: ${JSON.stringify(commit.date)},
  markdown: [
${markdownLines}
  ].join("\\n"),
} satisfies ProjectReadmeSnapshot;
`;
}

const commit = await fetchBranchHead();
const markdown = await fetchReadme(commit.sha);

await writeFile(outputPath, renderModule({ commit, markdown }), "utf8");
console.log(
  `Saved ${repo} README from ${commit.sha.slice(0, 7)} (${commit.date}) to ${path.relative(process.cwd(), outputPath)}`,
);
